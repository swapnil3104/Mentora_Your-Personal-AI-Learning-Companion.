from typing import List, Optional, Dict
from pydantic import BaseModel, Field
from enum import Enum

class RAGMode(str, Enum):
    STANDARD = "standard"
    SIMPLE_EXPLANATION = "simple_explanation"

class SourceCitation(BaseModel):
    chunk_id: str = Field(..., description="Unique chunk identifier")
    document_id: str = Field(..., description="ID of source document")
    document_name: str = Field(..., description="Filename / title of source document")
    page_number: int = Field(..., description="Page or slide number where content appears")
    relevance_score: float = Field(..., description="Cosine similarity score (0.0 to 1.0)")
    snippet: str = Field(..., description="Snippet of referenced content")

class RAGQueryRequest(BaseModel):
    query: str = Field(..., min_length=1, description="Student's natural-language question")
    user_id: str = Field(..., description="User ID for document isolation")
    document_id: Optional[str] = Field(None, description="Optional single document ID to scope retrieval")
    document_ids: Optional[List[str]] = Field(None, description="Optional multiple document IDs to scope retrieval")
    top_k: int = Field(5, ge=1, le=20, description="Number of chunks to retrieve")
    min_relevance: float = Field(0.35, ge=0.0, le=1.0, description="Minimum similarity threshold")
    mode: RAGMode = Field(RAGMode.STANDARD, description="Answer mode: standard academic or simple explanation")
    conversation_history: Optional[List[Dict[str, str]]] = Field(
        None, description="Recent conversation history [{'role': 'user'|'assistant', 'content': '...'}]"
    )
    model: Optional[str] = Field(None, description="Override LLM model name")

class RAGQueryResponse(BaseModel):
    query: str = Field(..., description="Normalized user question")
    answer: str = Field(..., description="Grounded response generated by LLM")
    sources: List[SourceCitation] = Field(default_factory=list, description="Programmatically verified source citations")
    mode: str = Field(..., description="Execution mode used")
    total_chunks_retrieved: int = Field(..., description="Number of chunks retrieved and passed to context")
    insufficient_context: bool = Field(False, description="Flagged true if retrieved documents lack sufficient info")
    latency_ms: float = Field(..., description="Total pipeline latency in milliseconds")
    model: str = Field(..., description="Model used for generation")
    thinking: Optional[str] = Field(None, description="Reasoning / thinking trace if produced by model")

class RAGRetrieveRequest(BaseModel):
    query: str = Field(..., min_length=1, description="Natural-language search query")
    user_id: str = Field(..., description="User ID for student isolation")
    document_id: Optional[str] = Field(None, description="Optional single document ID filter")
    document_ids: Optional[List[str]] = Field(None, description="Optional multi-document ID filter")
    top_k: int = Field(5, ge=1, le=20, description="Top K results to return")
    min_relevance: float = Field(0.35, ge=0.0, le=1.0, description="Minimum relevance threshold")

class RetrievedChunkDetail(BaseModel):
    chunk_id: str
    document_id: str
    document_name: str
    page_number: int
    token_count: int
    content: str
    relevance_score: float

class RAGRetrieveResponse(BaseModel):
    query: str
    count: int
    chunks: List[RetrievedChunkDetail]
    insufficient_context: bool

